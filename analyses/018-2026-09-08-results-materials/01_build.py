def table(name, columns, rows, note, tex=False):
    folder=HERE/'tables';folder.mkdir(exist_ok=True)
    lines=[f'# {name.replace("-"," ").title()}', '', note, '',
           '| '+' | '.join(columns)+' |', '| '+' | '.join(['---']*len(columns))+' |']
    lines += ['| '+' | '.join(str(c) for c in row)+' |' for row in rows]
    (folder/(name+'.md')).write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    if tex:
        def escape(s):
            return str(s).replace('%',r'\%').replace('_',r'\_').replace('κ',r'$\kappa$').replace('Δ',r'$\Delta$')
        lines=['% Analysis 018; generated by 01_build.py. See ../observations/INDEX.md and ../figure_data.json.',
               '% '+note, r'\begin{tabular}{'+'l'+'r'*(len(columns)-1)+'}',r'\toprule',
               ' & '.join(escape(c) for c in columns)+r' \\',r'\midrule']
        lines += [' & '.join(escape(c) for c in row)+r' \\' for row in rows]
        lines += [r'\bottomrule',r'\end{tabular}']
        (folder/(name+'.tex')).write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')


def tables(d):
    paired='Same eager full-validation pass for loss and R_model; 338 blocks, one seed. R_model is the draft S_model.'
